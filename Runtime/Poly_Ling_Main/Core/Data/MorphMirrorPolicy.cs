// Assets/Editor/Poly_Ling/Core/Data/MorphMirrorPolicy.cs
// ============================================================
// モーフのミラー適用規約（正典）
// ============================================================
//
// 【この規約の位置づけ】
//   モーフとミラーの関係についての規約は、本ファイルを正典とする。
//   他のファイル（MeshContext / MirrorPair / MirrorBaker / モーフ生成経路 / UI）は
//   ここを参照し、規約そのものを各所に書き写さないこと。
//   書き写すと、片方だけ直されて食い違い、後から読んだ人が判断できなくなる。
//
// ============================================================
// 1. ミラーは MeshContext 単位の機構であり、モーフもその機構に乗る
// ============================================================
//
//   PolyLing のミラーは3種類あり、いずれも MeshContext（または その MeshObject）に
//   紐づく機構である。モーフも MeshContext なので、同じ機構にそのまま乗せる。
//   モーフ専用のミラー実装を別に作らないこと。
//
//   ①表示ミラー
//       MeshContext.MirrorType(0:なし/1:分離/2:結合) ＋ MirrorAxis / MirrorDistance /
//       MirrorMaterialOffset。ミラー側の MeshContext も頂点実体も存在せず、
//       描画時に元頂点 i をミラー行列で写して見せるだけ（SymmetryMeshCache）。
//       頂点対応は i ↔ i で、統合も再番号付けも起きない。
//       → モーフ側にも同じミラー属性を継承させるだけで連動する。
//         リスト上のオブジェクトは増えず、頂点数も増えない。
//
//   ②派生ミラー実体
//       MeshType.MirrorSide / BakedMirror、BakedMirrorSourceIndex、
//       ModelContext.MirrorPairs の MirrorPair(Real/Mirror/VertexMap/BonePairMap/Axis)。
//       ミラー側が独立した MeshContext として実在する。
//       → 親が2オブジェクトなので、モーフも Real 側／Mirror 側の2オブジェクトになる。
//
//   ③一時ミラー
//       MirrorBaker.BakeInPlace が同一 MeshObject を N→2N に展開し、
//       MeshObject.MirrorBakeState(MirrorBakeResult) を持つ。
//       解除は UnbakeInPlace ＋ WriteBackMode。所有管理は TempMirrorController。
//       → 親を実体化するとき、その親に属するモーフも同じ MirrorBakeResult で
//         同時に展開・解除する。頂点数 N も境界判定も親と同一なので、
//         OldToNew / NewToOriginalIndex をそのまま共有できる。
//
// ============================================================
// 2. ①表示ミラーでは非対称モーフは原理的に表現できない
// ============================================================
//
//   ①には頂点実体が半身しかなく、反対側は「元頂点をミラー行列で写した像」である。
//   したがってモーフが頂点 i を動かせば、その像も必ず動く。
//   「左目だけ閉じる」ようなモーフは、①のままでは作れない。仕様上の制約であり、
//   実装で回避できるものではない。
//
//   非対称モーフを恒久的に持てるのは、両側の頂点実体を恒久的に持つ場合、
//   すなわち②か、そもそもミラー機構を持たない左右対称メッシュだけである。
//
//   → UI は、親が①のモーフに対して NoMirror / MirrorOf を選択させてはならない。
//
// ============================================================
// 3. ③一時ミラーは非対称モーフの置き場ではない
// ============================================================
//
//   ③は解除時に WriteBackMode（OriginalSideOnly / MirroredSideOnly / Average）で
//   どちらか片側が採用されるため、実体化中に作った左右差は解除時点で失われる。
//   ③は「対称モーフを両側同時に編集するための一時状態」であって、
//   非対称モーフを作って保持する場所ではない。
//
//   → 非対称モーフを作りたい場合は②へ変換してから作る。
//
// ============================================================
// 4. ②の Mirror 側モーフは派生物であり、直接編集しない
// ============================================================
//
//   ②では Real 側モーフを編集すると、Mirror 側モーフが自動同期される
//   （MirrorPair.SyncMorphSymmetric 経由）。
//   Mirror 側モーフを手で編集しても、次の同期で上書きされて失われる。
//
//   → UI は Mirror 側モーフを編集対象として出さず、Real 側の下に折り畳んで見せる。
//     ユーザーが名前を管理するのは MorphExpression の名前ひとつだけにする。
//
// ============================================================
// 5. ポリシーは MorphExpression（式レベル）ではなく MeshContext 側に置く
// ============================================================
//
//   ミラーが MeshContext 単位の機構である以上、ミラー適用の可否も MeshContext 側に
//   なければ①③に効かせられない。式レベルの真偽値では、
//   「どの実体にミラーを効かせるか」を表現できない。
//
//   MorphExpression.IsSymmetric は本ポリシー導入前の名残であり、参照してはならない。
//
// ============================================================

using System;

namespace Poly_Ling.Data
{
    /// <summary>
    /// モーフのミラー適用ポリシー。
    /// 規約は本ファイル冒頭のコメントを正典とする。
    /// </summary>
    /// <remarks>
    /// 【値の固定】リモート転送で (byte) として送出するため、
    /// 既存メンバの番号は変更しないこと。追加は必ず末尾に行う。
    /// </remarks>
    public enum MorphMirrorPolicy
    {
        /// <summary>
        /// 親メッシュのミラー設定に従う（既定）。対称モーフ。
        /// ①②③すべてで成立する。
        /// </summary>
        FollowParent = 0,

        /// <summary>
        /// ミラー機構から外す。片側だけに効くモーフ（例: ウインク左）。
        /// ②またはミラー機構を持たないメッシュでのみ意味を持つ。
        /// ①③で指定しても効果を持たない（正典コメントの 2. と 3. を参照）。
        /// </summary>
        NoMirror = 1,

        /// <summary>
        /// 他のモーフの左右反転として導出する。差分そのものは保持しない
        /// （例: ウインク左に対するウインク右）。
        /// 参照先は MeshContext.MirrorOfMorphIndex。
        /// 左右対応は ②=MirrorPair.VertexMap、③=MirrorBakeResult.NewToOriginalIndex、
        /// ミラー無しメッシュ=別途構築する対称頂点マップ で解決する。
        /// </summary>
        MirrorOf = 2
    }
}
